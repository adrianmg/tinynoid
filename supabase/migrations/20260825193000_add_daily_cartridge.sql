create table private.daily_cartridges (
  daily_id date primary key,
  level_id text not null references public.community_levels(id),
  run_seed integer not null check (run_seed between 0 and 2147483647),
  max_score integer not null check (max_score between 0 and 50000),
  created_at timestamptz not null default now()
);

create table private.daily_run_tickets (
  run_id uuid primary key,
  daily_id date not null references private.daily_cartridges(daily_id),
  level_id text not null references public.community_levels(id),
  token_hash text not null check (token_hash ~ '^[0-9a-f]{64}$'),
  issued_at timestamptz not null default now(),
  expires_at timestamptz not null,
  consumed_at timestamptz
);

create table public.daily_scores (
  id bigint generated by default as identity primary key,
  run_id uuid not null unique,
  daily_id date not null references private.daily_cartridges(daily_id),
  level_id text not null references public.community_levels(id),
  player_name text not null,
  score integer not null,
  outcome text not null,
  submitted_at timestamptz not null default now(),
  constraint daily_scores_player_name
    check (
      char_length(player_name) between 2 and 16
      and player_name ~ '^@[A-Z0-9_]{1,15}$'
    ),
  constraint daily_scores_score check (score between 0 and 50000),
  constraint daily_scores_outcome
    check (outcome in ('game_over', 'daily_clear'))
);

