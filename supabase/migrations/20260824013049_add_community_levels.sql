create or replace function private.is_valid_community_layout(p_layout text[])
returns boolean
language sql
immutable
set search_path = ''
as $$
  select
    coalesce(array_ndims(p_layout) = 1, false)
    and coalesce(cardinality(p_layout) = 10, false)
    and coalesce(bool_and(coalesce(
      octet_length(row_text) = 13
      and row_text ~ '^[.WOCGRBPYSX]{13}$',
      false
    )), false)
    and coalesce(sum(
      char_length(regexp_replace(row_text, '[.X]', '', 'g'))
    ), 0) >= 8
    and coalesce(sum(
      char_length(regexp_replace(row_text, '[.]', '', 'g'))
    ), 0) <= 100
  from unnest(p_layout) as rows(row_text);
$$;

revoke all on function private.is_valid_community_layout(text[])
  from public, anon, authenticated;

create table public.community_levels (
  id text primary key,
  schema_version smallint not null,
  level_name text not null,
  creator_display_name text not null,
  layout text[] not null,
  populated_count smallint not null,
  content_hash text not null unique,
  created_at timestamptz not null default now(),
  constraint community_levels_id_format
    check (id ~ '^cl_[0-9a-f]{24}$'),
  constraint community_levels_schema_version
    check (schema_version = 1),
  constraint community_levels_level_name
    check (
      char_length(level_name) between 2 and 32
      and level_name ~ '^[A-Z0-9 @._-]+$'
      and level_name = upper(
        regexp_replace(btrim(level_name), '[[:space:]]+', ' ', 'g')
      )
    ),
  constraint community_levels_creator_name
    check (
      char_length(creator_display_name) between 2 and 24
      and creator_display_name ~ '^[A-Z0-9 @._-]+$'
      and creator_display_name = upper(
        regexp_replace(
          btrim(creator_display_name),
          '[[:space:]]+',
          ' ',
          'g'
        )
      )
    ),
  constraint community_levels_layout
    check (private.is_valid_community_layout(layout)),
  constraint community_levels_populated_count
    check (populated_count between 8 and 100),
  constraint community_levels_content_hash
    check (content_hash ~ '^[0-9a-f]{64}$'),
  constraint community_levels_id_matches_hash
    check (id = 'cl_' || left(content_hash, 24))
);

create table private.community_level_moderation (
  level_id text primary key
    references public.community_levels(id),
  status text not null default 'pending',
  actor text not null default 'submission',
  reason text,
  status_changed_at timestamptz not null default now(),
  constraint community_level_moderation_status
    check (status in ('pending', 'listed', 'quarantined', 'removed')),
  constraint community_level_moderation_actor
    check (char_length(actor) between 1 and 128),
  constraint community_level_moderation_reason
    check (reason is null or char_length(reason) between 1 and 1000)
);

create table private.community_level_moderation_events (
  id bigint generated by default as identity primary key,
  level_id text not null references public.community_levels(id),
  previous_status text,
  new_status text not null,
  actor text not null,
  reason text,
  changed_at timestamptz not null default now(),
  constraint community_level_moderation_events_previous_status
    check (
      previous_status is null
      or previous_status in ('pending', 'listed', 'quarantined', 'removed')
    ),
  constraint community_level_moderation_events_new_status
    check (new_status in ('pending', 'listed', 'quarantined', 'removed')),
  constraint community_level_moderation_events_actor
    check (char_length(actor) between 1 and 128),
  constraint community_level_moderation_events_reason
    check (reason is null or char_length(reason) between 1 and 1000)
);

create table private.community_level_submission_limits (
  key_hash text primary key,
  window_started_at timestamptz not null,
  attempt_count integer not null,
  constraint community_level_submission_limits_key_hash
    check (key_hash ~ '^[0-9a-f]{64}$'),
  constraint community_level_submission_limits_attempt_count
    check (attempt_count between 1 and 32767)
);

